// Raw Knesset tables -> data.js: one row per person with the five clue values.
import { readFile, writeFile } from 'node:fs/promises';

const raw = async (t) => JSON.parse(await readFile(new URL(`../data/raw/${t}.json`, import.meta.url)));
const people = await raw('KNS_Person');
const rows = await raw('KNS_PersonToPosition');

// Faction names change every election ("הליכוד בהנהגת...", joint lists). Map each to a party lineage;
// the keyword found EARLIEST in the name wins, so a joint list counts as its leading party.
// ponytail: joint-list members from the junior party count as the lead party; per-person override if it matters.
const PARTIES = [
  ['הליכוד', /ליכוד|חרות|גוש חרות ליברלים/],
  ['העבודה', /מערך|העבודה(?! -? ?פועלי ציון)|מפלגת פועלי ארץ|המחנה הציוני|ישראל אחת/],
  ['אחדות העבודה', /אחדות העבודה/],
  ['רפ"י', /רפ"י|רשימת פועלים ישראלית/],
  ['מפ"ם', /פועלים (ה)?מאוחדת|השומר הצעיר/],
  ['מרצ', /מרצ|ר"ץ|המחנה הדמוקרטי|יחד והבחירה|^יחד$/],
  ['שינוי', /שינוי(?! ויוזמה)|התנועה הדמוקרטית/],
  ['כחול לבן', /כחול לבן|המחנה הממלכתי/],
  ['יש עתיד', /יש עתיד/],
  ['קדימה', /קדימה|אחריות לאומית/],
  ['התנועה', /^התנועה( בראשות ציפי לבני)?$/],
  ['ש"ס', /ש"ס|שס |התאחדות הספרדים/],
  ['יהדות התורה', /יהדות התורה|אגודת ישראל|דגל התורה/],
  ['המפד"ל / הבית היהודי', /מפלגה דתית לאומית|חזית דתית|המזרחי|מזרחי|הבית היהודי/],
  ['ימינה', /ימינה|הימין החדש/],
  ['הציונות הדתית', /הציונות הדתית/],
  ['האיחוד הלאומי', /האיחוד הלאומי|איחוד לאומי|מולדת|תקומה/],
  ['עוצמה יהודית', /עוצמה יהודית|עוצמה לישראל/],
  ['ישראל ביתנו', /ישראל ביתנו/],
  ['כולנו', /כולנו/],
  ['תקווה חדשה', /תקווה חדשה|הימין הממלכתי/],
  ['ישראל בעלייה', /ישראל בעלייה/],
  ['גשר', /^גשר$|גשר - מרכז/],
  ['צומת', /^צומת$/],
  ['תל"ם', /תל"ם/],
  ['הרשימה המשותפת', /הרשימה המשותפת/],
  ['חד"ש', /חד"ש|דמוקרטית לשלום|קומוניסט/],
  ['רע"ם', /רע"ם|רע"מ|הרשימה הערבית המאוחדת/],
  ['בל"ד', /בל"ד|ברית לאומית דמוקרטית|אלתג'מוע/],
  ['תע"ל', /תע"ל|התנועה הערבית להתחדשות|תנועה ערבית להתחדשות/],
  ['הציונים הכלליים / הליברלים', /ציונים כלליים|הציונים הכלליים|מפלגה ליברלית|ליברלים עצמאיים|פרוגרסיבית/],
  ['עם אחד', /עם אחד/],
  ['נעם', /^נעם/],
  ['התחייה', /תחייה/],
];

export function party(name) {
  name = name.trim();
  let best = null, at = Infinity;
  for (const [p, re] of PARTIES) {
    const m = name.match(re);
    if (m && m.index < at) { best = p; at = m.index; }
  }
  return best ?? name.replace(/^חה"כ .*/, 'סיעת יחיד');
}

const days = (r) => (new Date(r.FinishDate ?? Date.now()) - new Date(r.StartDate)) / 864e5;
const NICK = { 30657: 'בני גנץ', 2291: 'אריה דרעי' };

const ROLE = { 45: 3, 73: 3, 39: 2, 57: 2, 40: 1, 59: 1, 285079: 1 }; // רה"מ / שר / סגן שר; else ח"כ
const ROLE_NAME = ['ח"כ', 'סגן/ית שר', 'שר/ה', 'ראש ממשלה'];

const by = new Map();
for (const r of rows) (by.get(r.PersonID) ?? by.set(r.PersonID, []).get(r.PersonID)).push(r);

const out = [];
for (const p of people) {
  const rs = (by.get(p.PersonID) ?? []).filter((r) => r.StartDate);
  if (!rs.length) continue;
  rs.sort((a, b) => a.StartDate.localeCompare(b.StartDate));
  // Faction stints under a month are bookkeeping noise (e.g. Bennett "in" המחנה הממלכתי for 0 days in 2022).
  const factions = rs.filter((r) => r.FactionName?.trim() && days(r) >= 30);
  const parties = [...new Set(factions.map((r) => party(r.FactionName)))];
  const knessets = new Set(rs.filter((r) => r.PositionID === 43 || r.PositionID === 61).map((r) => r.KnessetNum));
  const role = Math.max(0, ...rs.map((r) => ROLE[r.PositionID] ?? 0));
  const minister = rs.find((r) => ROLE[r.PositionID] >= 2);
  const last = rs.at(-1);
  out.push({
    id: p.PersonID,
    name: NICK[p.PersonID] ?? `${p.FirstName.trim()} ${p.LastName.trim()}`,
    f: p.GenderID === 250 ? 1 : 0,
    party: factions.length ? party(factions.at(-1).FactionName) : '—',
    parties,
    since: +rs[0].StartDate.slice(0, 4),
    role,
    roleName: ROLE_NAME[role],
    ministerSince: minister ? +minister.StartDate.slice(0, 4) : null,
    knessets: knessets.size,
    lastYear: +(last.FinishDate ?? new Date().toISOString()).slice(0, 4),
    current: p.IsCurrent,
  });
}

// Same full name twice (e.g. two "חיים כהן") -> add first year so the guess list stays unambiguous.
const seen = {};
for (const o of out) seen[o.name] = (seen[o.name] ?? 0) + 1;
for (const o of out) if (seen[o.name] > 1) o.name += ` (${o.since})`;

// Daily pool: recognisable names only — ministers active since 2013, or sitting MKs in their 2nd+ Knesset.
const pool = out.filter((o) => (o.role >= 2 && o.lastYear >= 2013) || (o.current && o.knessets >= 2)).map((o) => o.id);

await writeFile(new URL('../data.js', import.meta.url),
  `// Generated by tools/build.mjs from the Knesset OData API. Do not edit.\nwindow.POLS=${JSON.stringify(out)};\nwindow.POOL=${JSON.stringify(pool)};\n`);
console.log('people', out.length, 'pool', pool.length);
